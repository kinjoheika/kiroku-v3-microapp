"""Build 02_seed.sql from the repo's data/*.csv (the six Sheet tabs).

Usage: python make_seed.py <path-to-repo-data-folder>
Times in the sheet have no timezone; they are stored as Asia/Manila (+08:00).
"""
import csv
import sys
from pathlib import Path

TZ = "+08:00"


def q(v):
    if v is None or v == "":
        return "null"
    return "'" + v.replace("'", "''") + "'"


def b(v):
    return "true" if v.strip().upper() == "TRUE" else "false"


def ts(v):
    return q(f"{v}{TZ}") if v else "null"


def rows(data, name):
    with open(data / f"{name}.csv", newline="", encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def insert(table, cols, values):
    lines = ",\n".join("  (" + ", ".join(v) + ")" for v in values)
    return f"insert into public.{table} ({', '.join(cols)}) values\n{lines};\n"


def main():
    data = Path(sys.argv[1])
    out = ["-- Generated by make_seed.py from data/*.csv. Run after 01_schema.sql.\n"]
    out.append(insert("users", ["user_id", "name", "role"],
        [[q(r["user_id"]), q(r["name"]), q(r["role"])] for r in rows(data, "Users")]))
    out.append(insert("kumiai", ["kumiai_id", "name"],
        [[q(r["kumiai_id"]), q(r["name"])] for r in rows(data, "Kumiai")]))
    out.append(insert("companies", ["company_id", "kumiai_id", "name"],
        [[q(r["company_id"]), q(r["kumiai_id"]), q(r["name"])] for r in rows(data, "Companies")]))
    out.append(insert("job_orders",
        ["jo_id", "jo_number", "company_id", "worker_name", "target_deployment_date",
         "work_category", "program_type", "active"],
        [[q(r["jo_id"]), q(r["jo_number"]), q(r["company_id"]), q(r["worker_name"]),
          q(r["target_deployment_date"]), q(r["work_category"]), q(r["program_type"]), b(r["active"])]
         for r in rows(data, "JobOrders")]))
    out.append(insert("tasks",
        ["task_id", "jo_id", "track", "task_name", "sort_order", "offset_days",
         "editor_id", "due_date", "done", "done_at"],
        [[q(r["task_id"]), q(r["jo_id"]), q(r["track"]), q(r["task_name"]), r["order"],
          r["offset_days"], q(r["editor_id"]), q(r["due_date"]), b(r["done"]), ts(r["done_at"])]
         for r in rows(data, "Tasks")]))
    out.append(insert("activity", ["activity_key", "task_id", "type", "activity_date", "activity_time"],
        [[q(f'{r["task_id"]}|{r["type"]}|{r["date"]}|{r["time"]}'), q(r["task_id"]), q(r["type"]),
          q(r["date"]), q(r["time"])] for r in rows(data, "Activity")]))
    Path(__file__).with_name("02_seed.sql").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
